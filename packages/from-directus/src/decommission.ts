/**
 * The decommission transaction: adopt users, roles and files, then drop the rest.
 *
 * This is the last step of the playbook (docs/migrating-from-directus.md, phase 6), as
 * SQL you review and run once the container is stopped. Nothing is renamed before
 * then, so the old API keeps working until the moment you choose.
 *
 * What it does, in one transaction:
 *   1. directus_users  → users: password → password_hash (argon2id verifies unchanged),
 *      tfa_secret → mfa_secret, first/last name → display_name, status values mapped,
 *      SSO identity kept (provider, external_identifier), Directus-only UI columns dropped.
 *   2. directus_roles  → roles with a `key` slug; directus_users.role → user_roles rows.
 *      (role_permissions come from the grants plan, run separately.)
 *   3. directus_files  → files with @allodium/storage's column names, ids preserved so
 *      every FK column and every stored URL keeps resolving.
 *   4. FK columns that pointed at directus_users / directus_files follow the renames
 *      automatically (Postgres rewrites the constraint); nothing to do.
 *   5. Drop every remaining directus_* table EXPLICITLY, in dependency order.
 *
 * The SQL is generated, not run — you run it, inside the transaction it already opens,
 * after a snapshot. The test battery runs it against a live Directus 11 and rolls back.
 */
import type { DecommissionPlan, Inventory } from './types.js';

export interface DecommissionOptions {
  usersTable?: string;
  rolesTable?: string;
  userRolesTable?: string;
  filesTable?: string;
  /**
   * Directus status → your status. Default maps active→active, invited/draft→invited,
   * suspended/archived→deactivated, which is the `user_status` vocabulary
   * @allodium/auth's session store understands out of the box.
   */
  statusMap?: Record<string, string>;
  /** Keep `directus_activity` / `directus_revisions` as an audit archive instead of dropping them. */
  keepAuditTables?: boolean;
  /** Create the `user_status` enum type and cast the column to it. Default true. */
  statusEnum?: boolean;
}

const ident = (s: string) => `"${s.replaceAll('"', '""')}"`;
const sqlString = (s: string) => `'${s.replaceAll("'", "''")}'`;

const ADOPTED = ['directus_users', 'directus_roles', 'directus_files'];

/**
 * Children before parents, from the FK graph the inventory recorded — so the list is
 * right for whichever Directus version this is, and no drop ever needs CASCADE.
 * Alphabetical among tables with no remaining dependents, for a stable diff.
 */
function dropOrder(inv: Inventory, keep: Set<string>): string[] {
  const pending = new Set(inv.directus.systemTables.filter((t) => !ADOPTED.includes(t) && !keep.has(t)));
  const out: string[] = [];
  while (pending.size) {
    // A table may go once nothing still pending references it.
    const ready = [...pending].filter((t) => !inv.directus.systemDependencies.some((d) => d.references === t && pending.has(d.table))).sort();
    if (!ready.length) {
      // A cycle (Directus has none today). Fall back to alphabetical; the transaction will say which one bites.
      out.push(...[...pending].sort());
      break;
    }
    for (const t of ready) {
      out.push(t);
      pending.delete(t);
    }
  }
  return out;
}

export function planDecommission(inv: Inventory, opts: DecommissionOptions = {}): DecommissionPlan {
  const users = opts.usersTable ?? 'users';
  const roles = opts.rolesTable ?? 'roles';
  const userRoles = opts.userRolesTable ?? 'user_roles';
  const files = opts.filesTable ?? 'files';
  const statusMap = opts.statusMap ?? { active: 'active', invited: 'invited', draft: 'invited', suspended: 'deactivated', archived: 'deactivated' };
  const statusEnum = opts.statusEnum ?? true;
  const notes: string[] = [];
  const have = new Set(inv.directus.systemTables);
  const L: string[] = [];
  const line = (...s: string[]) => L.push(...s);

  line('-- Generated by @allodium/from-directus. Review, snapshot, STOP THE CONTAINER, then run.', `-- Inventory taken ${inv.takenAt}; ${inv.users.total} users, ${inv.files.total} files, ${inv.collections.filter((c) => c.kind === 'table').length} tables.`, '', 'begin;', '');

  // Guards: refuse to run against a database that already has the target names.
  line('-- Refuse to run twice or against a database that already has the target tables.', 'do $$ begin');
  for (const t of [users, roles, userRoles, files]) line(`  if to_regclass(${sqlString(t)}) is not null then raise exception 'table % already exists; this transaction has run, or the name is taken', ${sqlString(t)}; end if;`);
  line('end $$;', '');

  /* ---------------------------------- users ---------------------------------- */
  line('-- 1. Users. Hashes are argon2id and verify unchanged; nobody resets a password.');
  line(`alter table directus_users rename to ${ident(users)};`);
  line(`alter table ${ident(users)} rename column password to password_hash;`);
  line(`alter table ${ident(users)} rename column tfa_secret to mfa_secret;`);
  line(`alter table ${ident(users)} rename column last_access to last_login_at;`);
  line(`alter table ${ident(users)} add column display_name varchar(120);`);
  line(`update ${ident(users)} set display_name = nullif(trim(concat_ws(' ', first_name, last_name)), '');`);
  line(`alter table ${ident(users)} add column created_at timestamptz not null default now();`);
  line(`alter table ${ident(users)} alter column email set not null;`);
  line(`alter table ${ident(users)} add constraint ${ident(`${users}_email_key`)} unique (email);`);
  if (inv.users.withoutPassword) {
    notes.push(`${inv.users.withoutPassword} user(s) have no password (SSO or never-set invites). password_hash stays nullable; @allodium/auth's verifyPassword treats null as "wrong password", and the /oidc entry point signs them in by provider + external_identifier.`);
  }
  line('-- Status vocabulary.');
  const cases = Object.entries(statusMap).map(([from, to]) => `when ${sqlString(from)} then ${sqlString(to)}`).join(' ');
  line(`update ${ident(users)} set status = case status ${cases} else status end;`);
  if (statusEnum) {
    const values = [...new Set(Object.values(statusMap))];
    line(`do $$ begin if to_regtype('user_status') is null then create type user_status as enum (${values.map(sqlString).join(', ')}); end if; end $$;`);
    line(`alter table ${ident(users)} alter column status drop default, alter column status type user_status using status::user_status, alter column status set default 'invited';`);
  }
  const unknownStatuses = Object.keys(inv.users.byStatus).filter((s) => !(s in statusMap));
  if (unknownStatuses.length) notes.push(`users have statuses the map does not cover: ${unknownStatuses.join(', ')} — pass statusMap or the enum cast will fail`);
  line('-- Columns only the Directus app used.');
  line(`alter table ${ident(users)}`);
  const uiCols = ['location', 'title', 'description', 'tags', 'language', 'token', 'last_page', 'auth_data', 'email_notifications', 'appearance', 'theme_dark', 'theme_light', 'theme_light_overrides', 'theme_dark_overrides', 'text_direction'];
  line(uiCols.map((c) => `  drop column if exists ${ident(c)}`).join(',\n') + ';');
  notes.push('users.avatar (uuid → files) is KEPT; it is a normal FK to your files table now.');
  notes.push(`users.first_name / last_name are kept beside display_name; drop them when nothing reads them.`);
  line('');

  /* ---------------------------------- roles ---------------------------------- */
  line('-- 2. Roles. A key slug is added; the matrix itself comes from the grants plan.');
  line(`alter table directus_roles rename to ${ident(roles)};`);
  line(`alter table ${ident(roles)} alter column id set default gen_random_uuid();`);
  line(`alter table ${ident(roles)} add column key varchar(40), add column label varchar(80), add column rank integer not null default 100;`);
  line(`update ${ident(roles)} set label = left(name, 80), key = left(regexp_replace(regexp_replace(lower(name), '[^a-z0-9]+', '_', 'g'), '^_+|_+$', '', 'g'), 40);`);
  line(`alter table ${ident(roles)} alter column key set not null, alter column label set not null, add constraint ${ident(`${roles}_key_key`)} unique (key);`);
  line(`alter table ${ident(roles)} drop column if exists icon, drop column if exists parent;`);
  line(`alter table ${ident(roles)} drop column name;`);
  line(`insert into ${ident(roles)} (id, key, label, description, rank) values (gen_random_uuid(), 'public', 'Public', 'Anonymous visitors. Anything granted here is readable by the whole internet.', 1000) on conflict (key) do nothing;`);
  notes.push(`roles keep their Directus uuid ids (role_permissions.role_id is uuid in this plan, not serial). The grants plan's SQL joins by key, so it does not care.`);
  line('');
  line(`create table ${ident(userRoles)} (`);
  line(`  user_id    uuid not null references ${ident(users)}(id) on delete cascade,`);
  line(`  role_id    uuid not null references ${ident(roles)}(id) on delete cascade,`);
  line(`  granted_at timestamptz not null default now(),`);
  line(`  granted_by uuid references ${ident(users)}(id) on delete set null,`);
  line(`  primary key (user_id, role_id)`);
  line(`);`);
  line(`insert into ${ident(userRoles)} (user_id, role_id) select id, role from ${ident(users)} where role is not null;`);
  line(`alter table ${ident(users)} drop column role;`);
  line('');
  line(`create table role_permissions (`);
  line(`  id         serial primary key,`);
  line(`  role_id    uuid not null references ${ident(roles)}(id) on delete cascade,`);
  line(`  table_name varchar(120) not null,`);
  line(`  can_create boolean not null default false,`);
  line(`  can_read   boolean not null default false,`);
  line(`  can_update boolean not null default false,`);
  line(`  can_delete boolean not null default false,`);
  line(`  row_filter jsonb,`);
  line(`  unique (role_id, table_name)`);
  line(`);`);
  line(`comment on column role_permissions.row_filter is 'Predicates restricting which rows this grant covers. Null or [] means every row. $actor.<claim> resolves per request.';`);
  line('');

  /* ---------------------------------- files ---------------------------------- */
  line('-- 3. Files. Ids preserved; columns take @allodium/storage names.');
  line(`alter table directus_files rename to ${ident(files)};`);
  line(`alter table ${ident(files)} rename column filename_disk to disk_name;`);
  line(`alter table ${ident(files)} rename column filename_download to filename;`);
  line(`alter table ${ident(files)} rename column type to mime_type;`);
  line(`alter table ${ident(files)} rename column filesize to filesize_bytes;`);
  line(`alter table ${ident(files)} rename column uploaded_on to uploaded_at;`);
  line(`update ${ident(files)} set uploaded_at = coalesce(uploaded_at, created_on);`);
  line(`alter table ${ident(files)} alter column uploaded_at set not null, alter column uploaded_at set default now();`);
  line(`alter table ${ident(files)} alter column disk_name set not null, add constraint ${ident(`${files}_disk_name_key`)} unique (disk_name);`);
  line(`alter table ${ident(files)}`);
  line(['storage', 'folder', 'charset', 'embed', 'location', 'tags', 'focal_point_x', 'focal_point_y', 'tus_id', 'tus_data', 'modified_by', 'modified_on', 'created_on'].map((c) => `  drop column if exists ${ident(c)}`).join(',\n') + ';');
  notes.push('files keeps width, height, duration, description, metadata and uploaded_by (→ users.id); drop what you do not read.');
  const nonLocal = Object.entries(inv.files.byStorage).filter(([s]) => s !== 'local');
  if (nonLocal.length) notes.push(`the storage column is dropped, but ${nonLocal.map(([s, n]) => `${n} file(s) were in "${s}"`).join(', ')} — copy those into your storage root FIRST`);
  line('');

  /* ---------------------------------- drops ---------------------------------- */
  const keep = new Set((opts.keepAuditTables ? ['directus_activity', 'directus_revisions'] : []).filter((t) => have.has(t)));
  const drops = dropOrder(inv, keep);
  line('-- 4. Drop every remaining directus_* table, explicitly, children first (order taken from the FK graph). No CASCADE anywhere.');
  for (const t of drops) line(`drop table ${ident(t)};`);
  if (keep.size) {
    line(`-- Kept as an audit archive: ${[...keep].join(', ')}`);
    for (const t of keep) {
      // The archive tables reference versions/users through FKs; those constraints are dropped so the archive stands alone.
      line(`do $$ declare c record; begin for c in select conname from pg_constraint where conrelid = ${sqlString(t)}::regclass and contype = 'f' loop execute format('alter table %I drop constraint %I', ${sqlString(t)}, c.conname); end loop; end $$;`);
      line(`alter table ${ident(t)} rename to ${ident(t.replace('directus_', 'archive_'))};`);
    }
    notes.push(`audit archive kept as ${[...keep].map((t) => t.replace('directus_', 'archive_')).join(', ')} with their FKs dropped`);
  }
  line('', '-- 5. Nothing named directus_* should remain.');
  line(`do $$ declare n int; begin select count(*) into n from information_schema.tables where table_schema = current_schema() and table_name like 'directus\\_%'; if n > 0 then raise exception '% directus_* table(s) remain', n; end if; end $$;`);
  line('', 'commit;', '');

  return { sql: L.join('\n'), drops, notes };
}
